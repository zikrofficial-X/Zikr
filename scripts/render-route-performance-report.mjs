import fs from 'node:fs';

const input = process.argv[2] ?? 'docs/audit-2026-08-22/route-performance.json';
const output = process.argv[3] ?? 'docs/audit-2026-08-22/route-performance-report-ar.md';
const data = JSON.parse(fs.readFileSync(input, 'utf8'));
const results = data.results;
const page = results.filter((r) => r.contentType.includes('text/html'));
const api = results.filter((r) => r.contentType.includes('application/json'));
const assets = results.filter((r) => !page.includes(r) && !api.includes(r));
const statusCounts = Object.entries(results.reduce((acc, r) => { acc[r.status] = (acc[r.status] ?? 0) + 1; return acc; }, {})).sort();
const slow = [...results].sort((a, b) => b.elapsedMs - a.elapsedMs).slice(0, 10);
const fmt = (n) => `${n.toFixed(2)} ms`;
const row = (r) => `| \`${r.route}\` | ${r.status} | ${r.ok ? 'ناجح' : 'فشل'} | ${fmt(r.elapsedMs)} | ${(r.bytes / 1024).toFixed(1)} KB | ${r.contentType || 'غير معروف'} |`;
const lines = [];
lines.push('# تقرير أداء مسارات ZIKR الإنتاجية');
lines.push('');
lines.push(`**النطاق:** ${data.summary.base}  `);
lines.push(`**وقت القياس:** ${data.summary.generatedAt}  `);
lines.push('**طريقة القياس:** طلب HTTP مباشر لكل مسار مع `redirect: manual` و`cache: no-store`، ويُقاس الزمن من بدء الطلب حتى قراءة جسم الاستجابة كاملًا. هذه ليست أرقام Lighthouse أو Real User Monitoring.');
lines.push('');
lines.push('## الملخص التنفيذي');
lines.push('');
lines.push(`تم فحص **${data.summary.checked} مسارًا**، ونجحت جميع الطلبات (**${data.summary.success} من ${data.summary.checked}**). تراوح زمن الاستجابة بين **${fmt(data.summary.minMs)}** و**${fmt(data.summary.maxMs)}**، وكان الوسيط **${fmt(data.summary.medianMs)}**. إجمالي البيانات المقروءة من الاستجابات بلغ **${(data.summary.totalBytes / 1024 / 1024).toFixed(2)} MB**.`);
lines.push('');
lines.push('| المقياس | القيمة |');
lines.push('|---|---:|');
lines.push(`| عدد المسارات | ${data.summary.checked} |`);
lines.push(`| الناجح | ${data.summary.success} |`);
lines.push(`| الفاشل | ${data.summary.failures} |`);
lines.push(`| الحد الأدنى | ${fmt(data.summary.minMs)} |`);
lines.push(`| الوسيط | ${fmt(data.summary.medianMs)} |`);
lines.push(`| الحد الأقصى | ${fmt(data.summary.maxMs)} |`);
lines.push(`| إجمالي حجم الاستجابات | ${(data.summary.totalBytes / 1024 / 1024).toFixed(2)} MB |`);
lines.push('');
lines.push('## توزيع الحالات');
lines.push('');
lines.push('| HTTP status | العدد | التفسير |');
lines.push('|---:|---:|---|');
for (const [status, count] of statusCounts) lines.push(`| ${status} | ${count} | ${status === '200' ? 'استجابة ناجحة' : 'تحتاج مراجعة حسب المسار'} |`);
lines.push('');
lines.push('## النتائج حسب الفئة');
lines.push('');
lines.push(`تم قياس **${page.length} صفحة HTML** و**${api.length} واجهة JSON** و**${assets.length} أصل ثابت/صوتي**.`);
lines.push('');
lines.push('| المسار | الحالة | النتيجة | الزمن | الحجم | نوع المحتوى |');
lines.push('|---|---:|---|---:|---:|---|');
for (const r of results) lines.push(row(r));
lines.push('');
lines.push('## أبطأ عشرة مسارات في هذه العينة');
lines.push('');
lines.push('| الترتيب | المسار | الزمن | الحجم | الحالة |');
lines.push('|---:|---|---:|---:|---:|');
slow.forEach((r, i) => lines.push(`| ${i + 1} | \`${r.route}\` | ${fmt(r.elapsedMs)} | ${(r.bytes / 1024).toFixed(1)} KB | ${r.status} |`));
lines.push('');
lines.push('## التفسير والحدود');
lines.push('');
lines.push('نجاح HTTP لا يثبت وحده اكتمال تجربة المستخدم أو صحة بيانات قاعدة البيانات أو أداء JavaScript بعد التحميل. المسارات الأبطأ في هذه الجولة هي مرشحون للمراجعة، لكن الزمن يتأثر ببرودة الوظيفة، وموقع نقطة القياس، واتصال الشبكة، وتزامن الطلبات. يلزم Lighthouse وReal User Monitoring لقياس LCP وINP وCLS وTTFB على أجهزة حقيقية.');
lines.push('');
lines.push('اختبار `/memorization` في تقارير smoke القديمة أعاد redirect محميًا للمستخدم غير المسجل، وهو سلوك متوقع وليس فشلًا. أما القياس الحالي على النطاق الإنتاجي canonical فقد أعاد نجاحًا لكل المسارات المدرجة.');
lines.push('');
fs.writeFileSync(output, `${lines.join('\n')}\n`);
console.log(output);
