import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
const read = (path) => readFileSync(resolve(process.cwd(), path), "utf8");
const writtenRoute = read("src/app/api/admin/social/written/route.ts");
const sectionsRoute = read("src/app/api/admin/sections/route.ts");
const pageViewRoute = read("src/app/api/admin/page-view/route.ts");
const videoRoute = read("src/app/api/admin/videos/[id]/route.ts");
const writtenPost = writtenRoute.slice(writtenRoute.indexOf("export async function POST"));
assert.match(writtenPost, /readBoundedJsonBody\(request\)/);
assert.doesNotMatch(writtenPost, /request\.json\(\)/);
assert.ok(writtenPost.indexOf("readBoundedJsonBody") < writtenPost.indexOf("parseWrittenGenerationRequest"));
const sectionsPost = sectionsRoute.slice(sectionsRoute.indexOf("export async function POST"));
assert.match(sectionsPost, /readBoundedJsonBody\(request, 8 \* 1024\)/);
assert.doesNotMatch(sectionsPost, /request\.json\(\)/);
assert.ok(sectionsPost.indexOf("readBoundedJsonBody") < sectionsPost.indexOf("normalizeVisibility"));
const pageViewPost = pageViewRoute.slice(pageViewRoute.indexOf("export async function POST"));
assert.match(pageViewPost, /requireAdminApi\(["']analytics\.read["']\)/);
assert.match(pageViewPost, /readBoundedJsonBody\(request, 4 \* 1024\)/);
assert.doesNotMatch(pageViewPost, /request\.json\(\)/);
assert.doesNotMatch(pageViewPost, /requireAdminPermission/);
assert.ok(pageViewPost.indexOf("requireAdminApi") < pageViewPost.indexOf("recordAdminPageView"));
const videoPatch = videoRoute.slice(videoRoute.indexOf("export async function PATCH"));
assert.match(videoPatch, /readBoundedJsonBody\(request\)/);
assert.doesNotMatch(videoPatch, /request\.json\(\)/);
assert.ok(videoPatch.indexOf("requireAdminStepUpApi") < videoPatch.indexOf("readBoundedJsonBody"));
console.log("Admin API request-body limit contracts passed.");
