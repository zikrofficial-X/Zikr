CREATE SCHEMA cron;

CREATE TABLE cron.job (
  jobid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jobname text NOT NULL,
  command text NOT NULL,
  schedule text NOT NULL,
  active boolean NOT NULL DEFAULT true
);

CREATE OR REPLACE FUNCTION cron.alter_job(
  job_id bigint,
  schedule text DEFAULT NULL,
  command text DEFAULT NULL,
  p_database text DEFAULT NULL,
  p_username text DEFAULT NULL,
  active boolean DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
AS $function$
BEGIN
  UPDATE cron.job AS current_job
  SET schedule = COALESCE($2, current_job.schedule),
      command = COALESCE($3, current_job.command),
      active = COALESCE($6, current_job.active)
  WHERE current_job.jobid = $1;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'cron job % was not found', job_id;
  END IF;
  RETURN job_id;
END;
$function$;

CREATE OR REPLACE FUNCTION cron.unschedule(job_id bigint)
RETURNS boolean
LANGUAGE plpgsql
AS $function$
BEGIN
  DELETE FROM cron.job WHERE cron.job.jobid = $1;
  RETURN FOUND;
END;
$function$;

CREATE OR REPLACE FUNCTION cron.schedule(
  p_jobname text,
  p_schedule text,
  p_command text
)
RETURNS bigint
LANGUAGE plpgsql
AS $function$
DECLARE
  created_job_id bigint;
BEGIN
  INSERT INTO cron.job (jobname, schedule, command, active)
  VALUES (p_jobname, p_schedule, p_command, true)
  RETURNING jobid INTO created_job_id;
  RETURN created_job_id;
END;
$function$;

